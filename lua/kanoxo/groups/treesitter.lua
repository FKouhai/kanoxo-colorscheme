local M = {}

function M.get(spec, config)
  local e = spec.editor
  local s = spec.syntax
  local d = spec.diag
  local g = spec.git
  local st = (config and config.styles) or {}
  local comment_italic = st.comments == nil and true or st.comments.italic ~= false
  local keyword_italic = st.keywords == nil and true or st.keywords.italic ~= false

  return {
    ["@variable"]              = { fg = e.fg },
    ["@variable.builtin"]      = { fg = s.constant, italic = true },
    ["@variable.parameter"]    = { fg = e.fg_dim },
    ["@variable.member"]       = { link = "@variable" },
    ["@constant"]              = { fg = s.constant },
    ["@constant.builtin"]      = { fg = s.constant, bold = true },
    ["@constant.macro"]        = { link = "Macro" },
    ["@string"]                = { fg = s.string },
    ["@string.regexp"]         = { fg = s.escape },
    ["@string.escape"]         = { fg = s.escape },
    ["@string.special"]        = { link = "@string.escape" },
    ["@string.special.url"]    = { fg = s.type, underline = true },
    ["@character"]             = { link = "@string" },
    ["@number"]                = { link = "Number" },
    ["@number.float"]          = { link = "Float" },
    ["@boolean"]               = { link = "Boolean" },
    ["@function"]              = { fg = s.func },
    ["@function.builtin"]      = { fg = s.func, italic = true },
    ["@function.macro"]        = { link = "Macro" },
    ["@function.call"]         = { link = "@function" },
    ["@function.method"]       = { link = "@function" },
    ["@function.method.call"]  = { link = "@function" },
    ["@constructor"]           = { fg = s.type },
    ["@operator"]              = { fg = s.operator },
    ["@keyword"]               = { fg = s.keyword, italic = keyword_italic or nil },
    ["@keyword.function"]      = { link = "@keyword" },
    ["@keyword.operator"]      = { fg = s.keyword },
    ["@keyword.import"]        = { link = "Include" },
    ["@keyword.return"]        = { link = "@keyword" },
    ["@keyword.exception"]     = { fg = d.error },
    ["@keyword.conditional"]   = { link = "@keyword" },
    ["@keyword.repeat"]        = { link = "@keyword" },
    ["@type"]                  = { fg = s.type },
    ["@type.builtin"]          = { fg = s.type, italic = true },
    ["@type.definition"]       = { link = "@type" },
    ["@attribute"]             = { fg = s.constant },
    ["@property"]              = { fg = e.fg_dim },
    ["@tag"]                   = { fg = s.tag },
    ["@tag.attribute"]         = { fg = s.constant },
    ["@tag.delimiter"]         = { fg = e.fg_dark },
    ["@punctuation.delimiter"] = { fg = e.fg_dark },
    ["@punctuation.bracket"]   = { fg = e.fg_dim },
    ["@punctuation.special"]   = { fg = s.special },
    ["@comment"]               = { fg = e.comment, italic = comment_italic or nil },
    ["@comment.todo"]          = { fg = d.warn, bold = true },
    ["@comment.error"]         = { fg = d.error, bold = true },
    ["@comment.warning"]       = { fg = d.warn },
    ["@module"]                = { link = "@variable" },
    ["@namespace"]             = { link = "@variable" },
    ["@label"]                 = { fg = s.keyword },
    ["@markup.heading"]        = { fg = s.func, bold = true },
    ["@markup.link"]           = { fg = s.type, underline = true },
    ["@markup.link.url"]       = { link = "@string.special.url" },
    ["@markup.raw"]            = { fg = s.string },
    ["@markup.italic"]         = { italic = true },
    ["@markup.bold"]           = { bold = true },
    ["@markup.strikethrough"]  = { strikethrough = true },
    ["@markup.list"]           = { fg = s.constant },
    ["@diff.plus"]             = { fg = g.add },
    ["@diff.minus"]            = { fg = g.delete },
    ["@diff.delta"]            = { fg = g.change },

    -- LSP semantic tokens -> treesitter/base, never palette directly
    ["@lsp.type.function"]      = { link = "@function" },
    ["@lsp.type.method"]        = { link = "@function.method" },
    ["@lsp.type.variable"]      = { link = "@variable" },
    ["@lsp.type.parameter"]     = { link = "@variable.parameter" },
    ["@lsp.type.property"]      = { link = "@property" },
    ["@lsp.type.class"]         = { link = "Structure" },
    ["@lsp.type.interface"]     = { link = "@type" },
    ["@lsp.type.struct"]        = { link = "Structure" },
    ["@lsp.type.enum"]          = { link = "@type" },
    ["@lsp.type.enumMember"]    = { link = "@constant" },
    ["@lsp.type.keyword"]       = { link = "@keyword" },
    ["@lsp.type.type"]          = { link = "@type" },
    ["@lsp.type.typeParameter"] = { link = "@type" },
    ["@lsp.type.namespace"]     = { link = "@namespace" },
    ["@lsp.type.decorator"]     = { link = "@attribute" },
    ["@lsp.type.comment"]       = { link = "@comment" },
    ["@lsp.type.string"]        = { link = "@string" },
    ["@lsp.type.number"]        = { link = "@number" },
    ["@lsp.type.operator"]      = { link = "@operator" },
    -- new-style `mod` (0.11+) aliases alongside legacy `typemod`
    ["@lsp.mod.defaultLibrary"] = { link = "@type.builtin" },
    ["@lsp.typemod.function.defaultLibrary"] = { link = "@function.builtin" },
    ["@lsp.typemod.variable.defaultLibrary"] = { link = "@variable.builtin" },
    ["@lsp.typemod.type.defaultLibrary"]     = { link = "@type.builtin" },
    ["@lsp.typemod.class.defaultLibrary"]    = { link = "@type.builtin" },
    ["@lsp.typemod.variable.readonly"]       = { link = "@constant" },
    ["@lsp.mod.readonly"]                    = { link = "@constant" },
  }
end

return M
